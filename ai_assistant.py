from typing import Any

from openai import OpenAI
from dotenv import load_dotenv
import os
import sys
from tools import TOOLS, get_tool_response
from utils import log, construct_response, construct_tool_calls_payload

load_dotenv()

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

client = OpenAI(
    base_url=f"{os.getenv('BASE_URL')}/v1",
    api_key=os.getenv("API_KEY")
)

messages_history: list[dict[str, Any]] = []

max_tool_call_requests = max(1, int(os.getenv("MAX_TOOL_CALL_REQUESTS", "10")))

messages_history.append({
    "role": "system",
    "content": (
        "You are a helpful assistant."
        f"Don't exceed the {max_tool_call_requests} subsequent tool calls limit. "
        "Keep responses short and concise"
    ),
})

print("type exit to stop the conversation")

while True:
    try:
        query = input("\nSamman: ")
        if query.lower() == "exit":
            break
        messages_history.append({
            "role": "user",
            "content": query
        })

        for i in range(max_tool_call_requests):

            stream = client.chat.completions.create(
                    model=os.getenv("MODEL", ""),
                    messages=messages_history,
                    tools=TOOLS,
                    stream=True
                )

            message, tool_calls = construct_response(stream)

            if not tool_calls:
                break
            
            log(f"Step {i+1}: LLM requested {len(tool_calls)} tool call(s).")

            messages_history.append({
                "role":"assistant",
                "content":message,
                "tool_calls": construct_tool_calls_payload(tool_calls)
            })

            messages_history.extend(get_tool_response(tool_calls))

        else:

            messages_history.append({
                "role": "assistant",
                "content": "Error: Too many tool calls. Please try again."
                })
            print("Assistant: Too many tool calls. Please try again.")
            continue


        messages_history.append({
            "role": "assistant",
            "content": message if message else "No response generated by LLM."
        })

        print()
    except KeyboardInterrupt as e:
        print("\033[31mAgent loop stopped due to user interruption!\033[0m")
        break
    except Exception as e:
        print(F"\033[31mError occured while running agent loop: {e}\033[0m")
        break
    

